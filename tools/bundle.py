#!/usr/bin/env python3
"""Build dist/ThreatTide_full.vbs: every table module in load order, one file.

Paste the result into the .vpx script editor for the booth cabinet.

    python3 tools/bundle.py          # write the bundle
    python3 tools/bundle.py --check  # fail if the committed bundle is stale
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLE = ROOT / "table"
OUT = ROOT / "dist" / "ThreatTide_full.vbs"

# Same order as table/ThreatTide_loader.vbs
MODULES = [
    "tt_config.vbs",
    "tt_money.vbs",
    "tt_rules.vbs",
    "tt_sound.vbs",
    "tt_display.vbs",
    "tt_scores.vbs",
    "tt_table.vbs",
]

HEADER = """' =============================================================================
' Threat Tide — full table script (generated by tools/bundle.py, do not edit)
' Edit the files in table/ and rebuild. Paste this whole file into the
' .vpx script editor.
' =============================================================================
"""


def build() -> str:
    parts = [HEADER]
    for name in MODULES:
        text = (TABLE / name).read_text(encoding="utf-8")
        parts.append(f"\n' ----------------------------------------------------------------------------\n' {name}\n' ----------------------------------------------------------------------------\n")
        parts.append(text.rstrip() + "\n")
    # VPX's script editor is happiest with CRLF and plain ASCII
    out = "".join(parts).replace("—", "-").replace("\r\n", "\n").replace("\n", "\r\n")
    out.encode("ascii")  # raises if anything non-ASCII slipped in
    return out


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_bytes().decode("ascii") if OUT.exists() else ""
        if current != text:
            print("dist/ThreatTide_full.vbs is stale: run python3 tools/bundle.py")
            return 1
        print("bundle up to date")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
